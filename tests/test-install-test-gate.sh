#!/bin/sh
# Tests for install-test-gate: the opt-in commit gate a private layer installs into its own source
# repository. Real commits in scratch repositories, with the machine's global git config (and so its
# configured hooks) switched off, so only the gate under test runs.
set -u
here=$(cd "$(dirname "$0")" && pwd)
tool="$here/../private_dot_local/bin/executable_install-test-gate"
t=${TMPDIR:-/tmp}; t=${t%/}
tmp=$(mktemp -d "$t/test-install-test-gate.XXXXXX"); trap 'rm -rf "$tmp"' EXIT
export GIT_CONFIG_GLOBAL="$tmp/gitconfig"; : > "$GIT_CONFIG_GLOBAL"
git config --global user.name t; git config --global user.email t@t.invalid; git config --global commit.gpgsign false
# The generated hook runs the suite under git-staged-run: the SOURCE copy, put on PATH.
mkdir -p "$tmp/bin"; cp "$here/../private_dot_local/bin/executable_git-staged-run" "$tmp/bin/git-staged-run"
PATH="$tmp/bin:$PATH"; export PATH
pass=0; fail=0
ok()  { pass=$((pass + 1)); echo "ok:   $1"; }
bad() { fail=$((fail + 1)); echo "FAIL: $1"; }
check() { if eval "$2"; then ok "$1"; else bad "$1"; fi; }

mkrepo() { # mkrepo <dir> <suite-exit-code>
  rm -rf "$1"; git init -q "$1"; mkdir -p "$1/tests" "$1/docs" "$1/bin"
  printf '#!/bin/sh\necho suite-ran\nexit %s\n' "$2" > "$1/tests/run-all.sh"
  echo seed > "$1/README.md"; git -C "$1" add -A; git -C "$1" commit -qm seed --no-verify
}
commit_one() { # commit_one <repo> <path> -> exit status of the commit
  echo x >> "$1/$2"; git -C "$1" add "$2"; git -C "$1" commit -qm change > "$tmp/out" 2>&1
}

# Not a git checkout: nothing to do, nothing written.
mkdir -p "$tmp/plain"
sh "$tool" "$tmp/plain" --label x --skip-var SKIP_X > "$tmp/out" 2>&1; rc=$?
check "not a git checkout: exit 0, nothing written" '[ "$rc" = 0 ] && [ ! -e "$tmp/plain/.git" ]'

# Usage errors.
sh "$tool" > "$tmp/out" 2>&1; rc=$?
check "no arguments: usage, exit 2" '[ "$rc" = 2 ]'
mkrepo "$tmp/r" 1
sh "$tool" "$tmp/r" --label x --skip-var 'not a var' > "$tmp/out" 2>&1; rc=$?
check "a skip variable that is not a variable name is refused" '[ "$rc" = 2 ] && [ ! -e "$tmp/r/.git/hooks/pre-commit" ]'

# Installed with the default scope: everything but documentation runs the suite.
sh "$tool" "$tmp/r" --label "my layer" --skip-var SKIP_MY_TESTS > "$tmp/out" 2>&1; rc=$?
check "install: exit 0, an executable pre-commit written" '[ "$rc" = 0 ] && [ -x "$tmp/r/.git/hooks/pre-commit" ]'
commit_one "$tmp/r" bin/tool; rc=$?
check "a failing suite refuses a commit of a non-doc file" '[ "$rc" != 0 ] && grep -q "my layer" "$tmp/out" && grep -q SKIP_MY_TESTS "$tmp/out"'
git -C "$tmp/r" reset -q
commit_one "$tmp/r" docs/page.md; rc=$?
check "a documentation-only commit skips the suite" '[ "$rc" = 0 ] && ! grep -q suite-ran "$tmp/out" && ! grep -q "running the test suite" "$tmp/out"'
echo x >> "$tmp/r/bin/tool"; git -C "$tmp/r" add bin/tool
SKIP_MY_TESTS=1 git -C "$tmp/r" commit -qm skipped > "$tmp/out" 2>&1; rc=$?
check "the skip variable lets a deliberate WIP commit through" '[ "$rc" = 0 ]'
printf '#!/bin/sh\nexit 0\n' > "$tmp/r/tests/run-all.sh"; git -C "$tmp/r" add tests/run-all.sh
commit_one "$tmp/r" bin/tool; rc=$?
check "a passing suite lets the commit through" '[ "$rc" = 0 ]'
check "the gate says the suite is running before it runs" 'grep -q "running the test suite" "$tmp/out"'

# Installed with --paths: only matching staged paths run the suite.
mkrepo "$tmp/p" 1
sh "$tool" "$tmp/p" --label p --skip-var SKIP_P --paths '^(bin/|tests/)' > /dev/null 2>&1
commit_one "$tmp/p" other.txt; rc=$?
check "--paths: a non-matching path is not gated" '[ "$rc" = 0 ]'
commit_one "$tmp/p" bin/tool; rc=$?
check "--paths: a matching path is gated" '[ "$rc" != 0 ]'

# Never overwrites a pre-commit it did not write; re-installing over its own is fine.
mkrepo "$tmp/f" 0
printf '#!/bin/sh\n# someone else s hook\nexit 0\n' > "$tmp/f/.git/hooks/pre-commit"
sh "$tool" "$tmp/f" --label f --skip-var SKIP_F > "$tmp/out" 2>&1; rc=$?
check "a foreign pre-commit is refused and left untouched" '[ "$rc" = 1 ] && grep -q "someone else" "$tmp/f/.git/hooks/pre-commit"'
sh "$tool" "$tmp/r" --label "my layer" --skip-var SKIP_MY_TESTS > "$tmp/out" 2>&1; rc=$?
check "re-installing over its own hook succeeds" '[ "$rc" = 0 ]'
mkrepo "$tmp/l" 0
printf '#!/bin/sh\n# dotfiles-overlay pre-commit (generated by run_onchange_install-overlay-hooks.sh).\n' > "$tmp/l/.git/hooks/pre-commit"
sh "$tool" "$tmp/l" --label l --skip-var SKIP_L > "$tmp/out" 2>&1; rc=$?
check "the hook its predecessor generated is replaced" '[ "$rc" = 0 ] && grep -q "generated by install-test-gate" "$tmp/l/.git/hooks/pre-commit"'
mkrepo "$tmp/b" 0
printf '#!/bin/sh\n# dotfiles-base pre-commit (generated by run_onchange_install-git-hooks.sh).\n' > "$tmp/b/.git/hooks/pre-commit"
sh "$tool" "$tmp/b" --label b --skip-var SKIP_B > "$tmp/out" 2>&1; rc=$?
check "the base's own earlier hook is replaced (the base installs through this tool now)" '[ "$rc" = 0 ] && grep -q "generated by install-test-gate" "$tmp/b/.git/hooks/pre-commit"'

# The suite judges what is STAGED, in a real commit. The suite here fails when bin/tool says BAD.
mkrepo "$tmp/s" 0
printf '#!/bin/sh\n! grep -q BAD bin/tool\n' > "$tmp/s/tests/run-all.sh"; echo ok > "$tmp/s/bin/tool"
git -C "$tmp/s" add -A; git -C "$tmp/s" commit -qm base --no-verify
sh "$tool" "$tmp/s" --label s --skip-var SKIP_S > /dev/null 2>&1
echo BAD > "$tmp/s/bin/tool"; git -C "$tmp/s" add bin/tool; echo "fixed on disk" > "$tmp/s/bin/tool"
git -C "$tmp/s" commit -qm bad > "$tmp/out" 2>&1; rc=$?
check "staged BAD, fixed on disk only: the commit is refused" '[ "$rc" != 0 ] && [ "$(git -C "$tmp/s" show :bin/tool)" = BAD ]'
check "...and the unstaged edit is back on disk" '[ "$(cat "$tmp/s/bin/tool")" = "fixed on disk" ]'
echo ok2 > "$tmp/s/bin/tool"; git -C "$tmp/s" add bin/tool; echo BAD > "$tmp/s/bin/tool"
git -C "$tmp/s" commit -qm good > "$tmp/out" 2>&1; rc=$?
check "staged ok, BAD on disk only: the commit goes through, the edit kept" '[ "$rc" = 0 ] && [ "$(git -C "$tmp/s" show HEAD:bin/tool)" = ok2 ] && [ "$(cat "$tmp/s/bin/tool")" = BAD ]'
git -C "$tmp/s" checkout -q -- bin/tool
echo x >> "$tmp/s/bin/other"; git -C "$tmp/s" add bin/other
PATH="/usr/bin:/bin" git -C "$tmp/s" commit -qm nohelper > "$tmp/out" 2>&1; rc=$?
check "no git-staged-run on PATH: refused, never run on the working tree" '[ "$rc" != 0 ] && grep -q "git-staged-run is not installed" "$tmp/out"'

# A repository that ships tests/select-suites.sh: the hook hands it the staged paths (deletions too)
# and runs nothing else; run-all.sh here always fails, so calling it directly would refuse.
mkrepo "$tmp/sel" 1
cat > "$tmp/sel/tests/select-suites.sh" <<'EOF'
#!/bin/sh
[ "$1" = --run ] || exit 97
cat > "$SEL_LOG"
echo "select-suites: stand-in selector"
exit "$(cat "$SEL_RC" 2>/dev/null || echo 0)"
EOF
echo gone > "$tmp/sel/bin/old"; echo keep > "$tmp/sel/bin/tool"; git -C "$tmp/sel" add -A; git -C "$tmp/sel" commit -qm sel --no-verify
sh "$tool" "$tmp/sel" --label sel --skip-var SKIP_SEL > /dev/null 2>&1
export SEL_LOG="$tmp/sel.log" SEL_RC="$tmp/sel.rc"; echo 0 > "$SEL_RC"
git -C "$tmp/sel" rm -q bin/old
commit_one "$tmp/sel" bin/tool; rc=$?
check "with a selector: its pass lets the commit through, run-all.sh is not run directly" '[ "$rc" = 0 ] && ! grep -q suite-ran "$tmp/out"'
check "with a selector: it gets the staged paths, a deleted one included" 'grep -qx bin/tool "$SEL_LOG" && grep -qx bin/old "$SEL_LOG"'
check "with a selector: its one-line summary is shown" 'grep -q "select-suites: stand-in selector" "$tmp/out"'
echo 1 > "$SEL_RC"
commit_one "$tmp/sel" bin/tool; rc=$?
check "with a selector: its failure refuses the commit and names how to re-run" '[ "$rc" != 0 ] && grep -q "a selected suite failed" "$tmp/out" && grep -q "select-suites.sh --run" "$tmp/out"'
git -C "$tmp/sel" reset -q; : > "$SEL_LOG"
commit_one "$tmp/sel" docs/page.md; rc=$?
check "with a selector: a documentation-only commit still skips everything" '[ "$rc" = 0 ] && [ ! -s "$SEL_LOG" ]'

# The timing slot (fleet-slot, stubbed on PATH): another holder draws a warning, never a refusal.
mkrepo "$tmp/slot" 0
sh "$tool" "$tmp/slot" --label s --skip-var SKIP_S > /dev/null 2>&1
printf '#!/bin/sh\necho "held by other-session since 13:00 for 20 min: timed run"\nexit 1\n' > "$tmp/bin/fleet-slot"
chmod +x "$tmp/bin/fleet-slot"
commit_one "$tmp/slot" bin/tool; rc=$?
check "slot held by another session: the commit goes through, warned with the holder's name" '[ "$rc" = 0 ] && grep -q "warning: the timing slot is held by other-session" "$tmp/out"'
printf '#!/bin/sh\necho free\nexit 0\n' > "$tmp/bin/fleet-slot"
commit_one "$tmp/slot" bin/tool; rc=$?
check "slot free: no warning" '[ "$rc" = 0 ] && ! grep -q "timing slot" "$tmp/out"'
printf '#!/bin/sh\necho broken >&2\nexit 2\n' > "$tmp/bin/fleet-slot"
commit_one "$tmp/slot" bin/tool; rc=$?
check "fleet-slot failing: no warning, and the commit is not refused" '[ "$rc" = 0 ] && ! grep -q "timing slot" "$tmp/out"'
rm -f "$tmp/bin/fleet-slot"

echo "passed: $pass   failed: $fail"
[ "$fail" -eq 0 ]
